import { box, cone, cyl, sphere, type Part } from '../kit/parts';

/**
 * Опоры воздушных линий.
 *
 * На промысле их 2877 только по ВЛ-10 кВ — это самый массовый объект после
 * фонда скважин, и от того, как они выглядят, зависит вид всего промысла с
 * высоты. Опоры железобетонные, стойка коническая (снизу толще), с траверсой
 * и штыревыми изоляторами.
 *
 * Ось траверсы — по X, то есть поперёк линии. При расстановке каждая опора
 * разворачивается по направлению своего пролёта.
 */

/** ВЛ-10 кВ: три провода на траверсе, высота подвеса около 9 м. */
export function buildPole10(): Part[] {
  const out: Part[] = [];
  const H = 10.5;

  // Стойка: коническая, заглублена в грунт
  out.push(cone('concrete', 0.13, 0.21, H, 0, H / 2 - 0.9, 0, 0, 0, 0, 8));
  // Основание-подсыпка вокруг комля
  out.push(cyl('concrete', 0.42, 0.25, 0, 0.1, 0, 0, 0, 0, 8));

  // Траверса и подкосы
  out.push(box('steel', 2.3, 0.09, 0.12, 0, H - 1.2, 0));
  out.push(box('steel', 0.9, 0.06, 0.06, -0.55, H - 1.5, 0, 0, 0.55));
  out.push(box('steel', 0.9, 0.06, 0.06, 0.55, H - 1.5, 0, 0, -0.55));

  // Три штыревых изолятора: два на траверсе, один на вершине
  for (const x of [-1.0, 1.0]) {
    out.push(cyl('steel', 0.03, 0.16, x, H - 1.06, 0, 0, 0, 0, 6));
    out.push(cone('insulation', 0.09, 0.12, 0.2, x, H - 0.88, 0, 0, 0, 0, 8));
    out.push(cone('insulation', 0.12, 0.07, 0.12, x, H - 0.72, 0, 0, 0, 0, 8));
  }
  out.push(cyl('steel', 0.03, 0.16, 0, H - 0.28, 0, 0, 0, 0, 6));
  out.push(cone('insulation', 0.09, 0.12, 0.2, 0, H - 0.1, 0, 0, 0, 0, 8));
  out.push(cone('insulation', 0.12, 0.07, 0.12, 0, 0.06 + H - 0.1, 0, 0, 0, 0, 8));

  // Заземляющий спуск вдоль стойки
  out.push(box('steelDark', 0.03, H - 1.2, 0.03, 0.17, (H - 1.2) / 2 - 0.5, 0.1));

  return out;
}

/** ВЛ-0,4 кВ: опора ниже, четыре провода, изоляторы мельче. */
export function buildPole04(): Part[] {
  const out: Part[] = [];
  const H = 7.5;

  out.push(cone('concrete', 0.1, 0.16, H, 0, H / 2 - 0.7, 0, 0, 0, 0, 8));
  out.push(cyl('concrete', 0.32, 0.2, 0, 0.08, 0, 0, 0, 0, 8));

  out.push(box('steel', 1.3, 0.07, 0.09, 0, H - 0.9, 0));
  for (const x of [-0.5, -0.17, 0.17, 0.5]) {
    out.push(cyl('steel', 0.022, 0.12, x, H - 0.78, 0, 0, 0, 0, 6));
    out.push(cone('insulation', 0.06, 0.08, 0.14, x, H - 0.66, 0, 0, 0, 0, 6));
  }
  out.push(sphere('steelDark', 0.05, 0, H - 0.55, 0));

  return out;
}
