import { useEffect } from 'react';

/**
 * МАСШТАБ ИНТЕРФЕЙСА ПОД РАЗМЕР ЭКРАНА.
 *
 * Показ идёт не на том мониторе, на котором его собирали. Вёрстка набрана в
 * пикселях — шестьдесят фиксированных размеров текста только в панелях, — и на
 * экране зала всё это осталось бы ровно таким же по числу пикселей: на
 * четырёхкратном разрешении подписи модулей стали бы нечитаемой сыпью.
 *
 * Правится одним рычагом, а не переписыванием шести десятков размеров.
 * `zoom` на слое интерфейса масштабирует и текст, и отступы, и границы блоков
 * согласованно, сохраняя раскладку: в отличие от `transform: scale`, он
 * пересчитывает саму раскладку, а не растягивает готовую картинку, поэтому
 * ничего не размывается и не уезжает за края.
 *
 * ВАЖНО ПРО ЕДИНИЦЫ. Внутри масштабированного слоя `vh` и `vw` продолжают
 * считаться от НЕмасштабированного окна: коробка в 56vh при двукратном
 * увеличении стала бы высотой в 112% экрана. Поэтому во всех панелях
 * ограничения по высоте переведены на проценты от слоя — слой сам занимает
 * ровно экран, и процент от него честно означает долю экрана.
 *
 * Считается по МЕНЬШЕЙ стороне относительно базовой раскладки: широкий и
 * низкий экран не должен раздувать интерфейс так, чтобы панели перестали
 * помещаться по высоте.
 *
 * Нижняя граница ниже единицы оставлена ради ноутбуков с малым разрешением,
 * верхняя ограничена двойкой: дальше интерфейс начинает съедать кадр, ради
 * которого всё и построено.
 */

/** Раскладка собрана и выверена на этом размере окна. */
const BASE_W = 1440;
const BASE_H = 860;

const MIN_SCALE = 0.85;
const MAX_SCALE = 2;

export function useUiScale(): void {
  useEffect(() => {
    const apply = () => {
      const raw = Math.min(
        globalThis.innerWidth / BASE_W,
        globalThis.innerHeight / BASE_H,
      );
      const scale = Math.min(MAX_SCALE, Math.max(MIN_SCALE, raw));
      // Округление до сотых, иначе при плавном изменении окна пересчёт
      // раскладки идёт на каждый пиксель протяжки.
      document.documentElement.style.setProperty('--ui-scale', scale.toFixed(2));
    };

    apply();
    globalThis.addEventListener('resize', apply);
    return () => globalThis.removeEventListener('resize', apply);
  }, []);
}
