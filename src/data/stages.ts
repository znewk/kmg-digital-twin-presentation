/**
 * Такт внутри этапа — минимальная единица нарратива. Панель модуля, смена
 * ракурса или включение слоя. Всё, что происходит в такте, обязано быть чистой
 * функцией от прогресса: иначе скролл вверх не отыграется.
 */
export interface Beat {
  id: string;
  cam: CamId;
  /** Заголовок такта. */
  title: T;
  /** Подпись под заголовком. */
  body?: T;
  /** 2D-панель модуля, в которую «проваливаемся». */
  panel?: PanelId;
  /** Модули, чьи бейджи подсвечиваются на этом такте. */
  modules?: ModuleId[];
  /** Объекты сцены в фокусе. */
  focus?: string[];
}

