import {
  box,
  cone,
  cyl,
  flange,
  gableRoof,
  ladder,
  pipe,
  pipeRun,
  railing,
  sphere,
  torus,
  valve,
  type Part,
} from '../kit/parts';

/**
 * Сборный пункт — СП «Молдабек», СП-16, «Мини СП N43».
 *
 * Сюда сходится весь нефтесбор промысла. Технология: продукция скважин
 * разделяется в сепараторах на нефть, воду и попутный газ. Нефть уходит
 * напорным нефтепроводом на ЦППН «Кенбай» за границей участка, вода — на КНС в
 * систему ППД, газ — на факел.
 *
 * Отсюда состав: горизонтальные сепараторы на седловых опорах (их видно
 * издалека и они узнаваемы), узел учёта, насосы откачки, дренажная ёмкость и
 * газовый стояк. Сепараторы горизонтальные, а не вертикальные, потому что при
 * больших расходах жидкости с высокой вязкостью нужна длинная зона отстоя.
 *
 * Что СП «Молдабек» — именно сборный пункт, известно из чертежа: подпись взята
 * из его текстового слоя и согласуется с «СП В-Молдабек» из карты объектов
 * сценария. Расположен на востоке, рядом с фактическим факелом.
 */

const PAD_W = 34;
const PAD_D = 22;

/** Горизонтальный сепаратор на двух седловых опорах, с лестницей и обвязкой. */
function separator(x: number, z: number, len: number, r: number): Part[] {
  const y = 2.6;
  const out: Part[] = [
    cyl('insulation', r, len, x, y, z, 0, 0, Math.PI / 2, 18),
    cone('insulation', r * 0.45, r, r * 0.55, x - len / 2 - r * 0.28, y, z, 0, 0, Math.PI / 2, 18),
    cone('insulation', r, r * 0.45, r * 0.55, x + len / 2 + r * 0.28, y, z, 0, 0, Math.PI / 2, 18),
  ];

  // Седловые опоры на бетонных тумбах
  for (const dx of [-len * 0.3, len * 0.3]) {
    out.push(box('concrete', 1.2, 1.5, r * 2.2, x + dx, 0.75, z));
    out.push(box('steelDark', 0.5, 0.9, r * 2.0, x + dx, 1.9, z));
  }

  // Кольца жёсткости, люк-лаз, уровнемер, предохранительный клапан
  for (const k of [-0.3, 0.15]) {
    out.push(torus('steel', r + 0.02, 0.06, x + len * k, y, z, 0, 0, Math.PI / 2));
  }
  out.push(cyl('steelDark', r * 0.32, 0.2, x - len * 0.42, y + r * 0.75, z, 0, 0, 0, 12));
  out.push(box('glass', 0.1, r * 1.3, 0.07, x + len * 0.34, y, z + r + 0.05));
  out.push(cyl('steel', 0.12, 0.6, x + len * 0.2, y + r + 0.3, z, 0, 0, 0, 8));

  // Площадка обслуживания сверху и лестница к ней
  out.push(box('steel', len * 0.7, 0.08, 1.2, x, y + r + 0.06, z - r * 0.55));
  out.push(...railing(x, y + r + 0.1, z - r * 0.55, len * 0.7, 1.2, 1.05));
  out.push(...ladder(x - len * 0.4, 0.4, z - r * 0.55, y + r - 0.3));

  return out;
}

export function buildSp(): Part[] {
  const out: Part[] = [];

  // ── Площадка и обваловка ─────────────────────────────────────────────────
  out.push(box('concrete', PAD_W, 0.4, PAD_D, 0, 0.2, 0));
  for (const [dx, dz, w, d] of [
    [0, -PAD_D / 2 - 1, PAD_W + 4, 2],
    [0, PAD_D / 2 + 1, PAD_W + 4, 2],
    [-PAD_W / 2 - 1, 0, 2, PAD_D + 4],
    [PAD_W / 2 + 1, 0, 2, PAD_D + 4],
  ] as const) {
    out.push(box('concrete', w, 0.9, d, dx, 0.45, dz));
  }

  // ── Три сепаратора ───────────────────────────────────────────────────────
  out.push(...separator(-7, -5.5, 11, 1.35));
  out.push(...separator(-7, 0.5, 11, 1.35));
  // Третий меньше — концевая ступень сепарации, давление ниже.
  out.push(...separator(-8.5, 6.2, 8, 1.05));

  // ── Входной коллектор нефтесбора ─────────────────────────────────────────
  const inX = -PAD_W / 2 - 1.6;
  out.push(
    ...pipeRun('pipe', 0.36, [
      [inX, 1.4, -8],
      [-15.5, 1.4, -8],
      [-15.5, 1.4, 0.5],
    ]),
  );
  out.push(...valve(-15.5, 1.55, -4, 1.3));
  for (const z of [-5.5, 0.5]) {
    out.push(pipe('pipe', 0.24, [-15.5, 1.4, z], [-13.2, 1.4, z]));
    out.push(flange('steelDark', 0.34, -13.4, 1.4, z, 0, 0, Math.PI / 2));
  }

  // ── Выход нефти: насосы откачки и напорный нефтепровод ───────────────────
  for (let i = 0; i < 2; i++) {
    const x = 4 + i * 4.2;
    out.push(box('steelDark', 3.4, 0.35, 1.4, x, 0.58, -6.5));
    out.push(cyl('painted', 0.5, 1.7, x - 0.9, 1.3, -6.5, 0, 0, Math.PI / 2, 14));
    out.push(cyl('steel', 0.44, 1.5, x + 0.95, 1.3, -6.5, 0, 0, Math.PI / 2, 14));
    out.push(pipe('pipe', 0.18, [x + 0.95, 1.3, -6.5], [x + 0.95, 2.5, -6.5]));
  }
  out.push(
    ...pipeRun('pipe', 0.3, [
      [-1.5, 1.9, -5.5],
      [12, 1.9, -5.5],
      [12, 1.9, -PAD_D / 2 - 1.8],
    ]),
  );
  out.push(...valve(12, 2.05, -9.5, 1.3));
  // Узел учёта нефти — то, чем меряют товарную продукцию.
  out.push(box('painted', 3.6, 3.0, 2.6, 12, 1.9, 3.5));
  out.push(...gableRoof('steel', 3.9, 2.9, 3.4, 0.5).map((p) => {
    p.matrix.elements[12] += 12;
    p.matrix.elements[14] += 3.5;
    return p;
  }));
  out.push(box('glass', 0.9, 0.7, 0.08, 12, 2.6, 2.16));
  out.push(cyl('accent', 0.22, 0.5, 10.2, 1.5, 1.6, 0, 0, 0, 10));

  // ── Выход воды на КНС ────────────────────────────────────────────────────
  out.push(
    ...pipeRun('pipeWater', 0.22, [
      [-7, 1.2, 6.2],
      [3, 1.2, 6.2],
      [3, 1.2, PAD_D / 2 + 1.8],
    ]),
  );
  out.push(...valve(3, 1.35, 9, 1.0));

  // ── Выход газа: стояк и сброс на факел ───────────────────────────────────
  out.push(
    ...pipeRun('pipe', 0.16, [
      [-7, 4.1, -5.5],
      [-2, 4.1, -5.5],
      [-2, 7.5, -5.5],
      [-2, 7.5, -PAD_D / 2 - 1.8],
    ]),
  );
  for (const z of [-5.5, -9.5]) {
    out.push(box('steel', 0.14, 7.1, 0.14, -2, 0.4 + 3.55, z));
  }

  // ── Дренажная ёмкость (подземная, наружу выходит горловина) ──────────────
  out.push(cyl('steelDark', 1.3, 0.6, 16, 0.55, 8, 0, 0, 0, 14));
  out.push(cyl('steel', 0.36, 1.1, 16, 1.15, 8, 0, 0, 0, 10));
  out.push(sphere('steelDark', 0.38, 16, 1.7, 8));

  // ── Операторная ──────────────────────────────────────────────────────────
  out.push(box('painted', 7.5, 3.2, 4.2, -13, 2.0, 8.5));
  out.push(...gableRoof('steel', 7.9, 4.5, 3.6, 0.7).map((p) => {
    p.matrix.elements[12] += -13;
    p.matrix.elements[14] += 8.5;
    return p;
  }));
  for (let i = 0; i < 3; i++) {
    out.push(box('glass', 1.2, 0.9, 0.08, -15.2 + i * 2.2, 2.5, 6.36));
  }
  out.push(box('steelDark', 0.95, 2.1, 0.1, -9.9, 1.45, 6.36));
  out.push(box('steel', 2.0, 0.08, 1.2, -9.9, 0.44, 5.7));

  // Мачты освещения по углам площадки
  for (const [mx, mz] of [
    [-16, -9],
    [15, -9],
    [15, 9.5],
  ] as const) {
    out.push(cyl('steel', 0.12, 9.5, mx, 5.15, mz, 0, 0, 0, 8));
    out.push(box('steelDark', 1.6, 0.2, 0.34, mx, 9.9, mz, 0, -0.22));
  }

  return out;
}
