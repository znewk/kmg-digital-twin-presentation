import { box, cyl, ladder, pipe, type Part } from '../kit/parts';

/**
 * Вскрытая траншея с разрезом грунта (ТЗ §4.4.2).
 *
 * Показывается на одном фактическом участке нефтесбора — как ремонтный
 * шурф. Смысл в том, чтобы зритель увидел, как трубопровод на самом деле
 * уложен: подсыпка, труба, сигнальная лента, обратная засыпка. Из плана и
 * из линии на поверхности этого не понять, а вся система сбора на промысле
 * подземная.
 *
 * Разрез грунта послойный: почвенно-растительный слой, суглинок, песок.
 * Глубина заложения условная — в чертеже она не указана ни для одной трассы.
 *
 * Ориентация: траншея вытянута вдоль оси X, труба идёт по её дну.
 */

const LEN = 26;
const WIDTH = 2.4;
const DEPTH = 1.8;

/** Слои разреза сверху вниз: доля толщины и материал. */
const SOIL_LAYERS: [number, Parameters<typeof box>[0]][] = [
  [0.18, 'painted'],
  [0.52, 'concrete'],
  [0.3, 'insulation'],
];

export function buildTrench(): Part[] {
  const out: Part[] = [];

  // ── Стенки с послойным разрезом ──────────────────────────────────────────
  // Каждая стенка набирается из горизонтальных полос: так виден профиль
  // грунта, а не однородная серая плита.
  for (const sign of [-1, 1]) {
    let top = 0;
    for (const [share, mat] of SOIL_LAYERS) {
      const h = DEPTH * share;
      out.push(box(mat, LEN, h, 0.35, 0, top - h / 2, sign * (WIDTH / 2 + 0.17)));
      top -= h;
    }
    // Бровка: валик вынутого грунта вдоль траншеи
    out.push(box('concrete', LEN, 0.5, 1.5, 0, 0.25, sign * (WIDTH / 2 + 1.1)));
  }

  // Торцевые стенки — иначе траншея выглядит бесконечной трубой в пустоте
  for (const sx of [-1, 1]) {
    let top = 0;
    for (const [share, mat] of SOIL_LAYERS) {
      const h = DEPTH * share;
      out.push(box(mat, 0.35, h, WIDTH, (sx * LEN) / 2, top - h / 2, 0));
      top -= h;
    }
  }

  // ── Дно: песчаная подсыпка ───────────────────────────────────────────────
  out.push(box('insulation', LEN, 0.22, WIDTH, 0, -DEPTH + 0.11, 0));

  // ── Труба на подсыпке ────────────────────────────────────────────────────
  const pipeY = -DEPTH + 0.42;
  out.push(cyl('pipe', 0.16, LEN, 0, pipeY, 0, 0, 0, Math.PI / 2, 12));
  // Сварные стыки через каждые 11 м — длина трубной секции
  for (const sx of [-0.42, 0.42]) {
    out.push(cyl('steelDark', 0.185, 0.12, sx * LEN, pipeY, 0, 0, 0, Math.PI / 2, 12));
  }
  // Опорные мешки под трубу на подсыпке
  for (let i = -2; i <= 2; i++) {
    out.push(box('insulation', 0.5, 0.2, 0.9, i * 5, -DEPTH + 0.31, 0));
  }

  // ── Сигнальная лента над трубой ──────────────────────────────────────────
  // Кладётся на 30–40 см выше трубы: при раскопке экскаватор задевает её
  // раньше, чем трубу. Ради этого она и существует.
  out.push(box('accent', LEN, 0.02, 0.28, 0, pipeY + 0.55, 0));

  // ── Частичная обратная засыпка с одного конца ────────────────────────────
  // Показывает, что траншея не декоративная канава, а этап работ.
  out.push(box('concrete', 6, DEPTH * 0.55, WIDTH - 0.1, LEN / 2 - 3, -DEPTH + DEPTH * 0.28, 0));
  out.push(box('concrete', 5, 0.6, 2.6, LEN / 2 - 3, 0.3, 0));

  // ── Обстановка участка работ ─────────────────────────────────────────────
  out.push(...ladder(-LEN / 2 + 2, -DEPTH, WIDTH / 2 - 0.3, DEPTH + 0.4));

  // Ограждение зоны работ: стойки с ленточным поручнем по обеим бровкам
  for (const sign of [-1, 1]) {
    const z = sign * (WIDTH / 2 + 2.1);
    for (let i = 0; i <= 6; i++) {
      const x = -LEN / 2 + (LEN * i) / 6;
      out.push(cyl('steel', 0.045, 1.1, x, 0.55, z, 0, 0, 0, 6));
    }
    out.push(pipe('accent', 0.03, [-LEN / 2, 1.05, z], [LEN / 2, 1.05, z], 4));
  }

  return out;
}
