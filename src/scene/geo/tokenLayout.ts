import * as THREE from 'three';
import { CAMS } from '../../data/stages';
import { GLOBE_R, MOLDABEK, localBasis, lonLatToVec3 } from './projection';

/**
 * ПОСАДКА ЗНАЧКА ПРОМЫСЛА НА КАРТУ И РАКУРС ОСМОТРА ЕГО ВБЛИЗИ.
 *
 * Здесь собрано всё, что относится к значку как к предмету на местности: чем он
 * стоит на заливке области, какого он размера, насколько сдвинут от координаты
 * площадки и с какой точки на него смотрит камера, когда его просят показать
 * вблизи. Сама сценка — в `FieldToken`; она про то, что нарисовано, а этот
 * модуль про то, где это стоит.
 *
 * Порознь эти числа не живут. Ракурс осмотра считается от габарита значка и его
 * смещения; стоит подвинуть значок и забыть про ракурс — камера встанет мимо.
 * Поэтому одна таблица на обоих потребителей: сцену и камеру.
 */

// ── Габарит сценки ──────────────────────────────────────────────────────────

/**
 * Размер сценки в единицах глобуса. Внутри `FieldToken` расстановка задана в
 * «метрах промысла», этот множитель переводит их в единицы значка.
 */
export const TOKEN_SCALE = 0.045;

/**
 * Габарит расстановки в её собственных единицах — по фактическим площадкам, а
 * не на глаз: западный край — отсыпка крайней качалки (−24 − 9), восточный —
 * обваловка сборного пункта (20 + 19 × 0,55), северный — площадка факела,
 * южный — линия опор ВЛ.
 *
 * Нужен дважды: чтобы посчитать, влезает ли значок в контур области, и чтобы
 * отвести камеру на осмотре ровно настолько, чтобы сценка заняла кадр.
 */
export const TOKEN_BOUNDS = { xMin: -33, xMax: 30.5, zMin: -19.5, zMax: 21 };

/**
 * ЗНАЧОК СДВИНУТ ВГЛУБЬ ОБЛАСТИ, А НЕ ПОСАЖЕН ЦЕНТРОМ НА КООРДИНАТУ.
 *
 * Молдабек Восточный лежит у самой восточной границы Атырауской области: от
 * площадки до границы 0,61° — около 3,2 единиц глобуса, а значок при читаемом
 * размере вдвое шире. Посаженный центром на координату, он вылезал восточным
 * краем — сборным пунктом и факелом — в соседнюю область. Карта в этот момент
 * говорит не «промысел вот здесь», а «границы нарисованы приблизительно».
 *
 * Поэтому расстановка сдвинута на запад, вглубь области. Координата площадки
 * остаётся ПОД значком — она приходится на его восточную часть, там, где стоит
 * сборный пункт, — то есть значок по-прежнему указывает на своё место, просто
 * растёт от него не во все стороны, а туда, где есть место.
 *
 * Смещение и размер подобраны вместе: при этих числах ближайшая точка контура
 * области остаётся примерно в единице глобуса (около 14 км по карте) от края
 * значка, и запас переживает и качание балансиров, и пульсацию ореола факела.
 */
export const LAYOUT_OFFSET: [number, number] = [-16, -1];

/**
 * Множитель экранного размера: сколько единиц значка приходится на единицу
 * расстояния до камеры. Держит постоянную крупность на экране, пока камера
 * подходит к области с орбиты.
 */
const TOKEN_SCREEN = 0.036;

/**
 * Радиус, на котором стоит значок.
 *
 * Значок — предмет, СТОЯЩИЙ на карте, и при осмотре вблизи любой зазор читается
 * тем, что промысел висит над областью. Прежние 1,006 давали больше единицы
 * просвета: с отвесного ракурса это не видно, с пологого видно сразу.
 *
 * Число не равно номинальному радиусу заливки (1,0022). Заливка — плоская
 * триангуляция, натянутая на сферу вершинами, и её грани идут хордами: под
 * площадкой Молдабека фактическая поверхность лежит на 300,60, то есть на 0,06
 * ниже номинала. Значок посажен на ФАКТИЧЕСКУЮ поверхность, иначе он стоял бы
 * на этой разнице.
 */
export const TOKEN_R = GLOBE_R * 1.002;

/** Точка привязки значка — фактическая координата площадки. */
export const TOKEN_ANCHOR = lonLatToVec3(MOLDABEK[0], MOLDABEK[1], TOKEN_R);

/** Местный горизонт площадки: значок стоит по нему, камера от него считается. */
export const TOKEN_BASIS = localBasis(MOLDABEK[0], MOLDABEK[1]);

/**
 * Разворот значка по местному горизонту: вверх — нормаль к поверхности,
 * вправо — восток, вниз по экрану — юг.
 *
 * Сценка построена в обычных координатах — «вверх» у неё по оси Y. На сфере
 * вверх у каждой точки своё направление; без разворота качалки на широте
 * Атырау лежали бы на боку.
 *
 * Базис задан явно, а не «кратчайшей дугой»: доворот вокруг нормали на
 * произвольный угол ставил план промысла на карту наискось — ряды качалок шли
 * по диагонали, коллектор наперекос к контуру области.
 */
export const TOKEN_QUAT = new THREE.Quaternion().setFromRotationMatrix(
  new THREE.Matrix4().makeBasis(TOKEN_BASIS.east, TOKEN_BASIS.up, TOKEN_BASIS.south),
);

/**
 * Опорная дистанция — от кадра этапа до значка.
 *
 * Берётся из самого ракурса, а не вписана числом: на ней значок имеет ту
 * крупность, которую для него и подбирали, и она же становится его размером в
 * мире, когда камера идёт смотреть промысел вблизи.
 */
export const TOKEN_REF_DIST = new THREE.Vector3(
  CAMS.atyrauFramed.p[0],
  CAMS.atyrauFramed.p[1],
  CAMS.atyrauFramed.p[2],
).distanceTo(TOKEN_ANCHOR);

/** Единица расстановки в единицах мира на кадре этапа. */
export const TOKEN_WORLD_SCALE = TOKEN_SCALE * TOKEN_SCREEN * TOKEN_REF_DIST;

/**
 * Масштаб значка: от постоянного экранного к постоянному мировому.
 *
 * ЗАЧЕМ ДВА РЕЖИМА. Пока камера подходит к области с орбиты, значок обязан
 * держать размер на экране: дистанция меняется на порядок, и при постоянном
 * размере в мире он был бы то точкой, то во весь кадр.
 *
 * Но ровно это же правило делает бессмысленным осмотр вблизи: камера подходит,
 * значок ужимается ей навстречу и остаётся той же величины на экране —
 * приближение не читается вовсе. Поэтому на осмотре размер фиксируется тем,
 * какой он был на кадре этапа, и дальше промысел растёт в кадре сам, как
 * настоящий предмет, к которому подходят.
 */
export function tokenScale(cameraDist: number, closeBlend: number): number {
  return THREE.MathUtils.lerp(
    cameraDist * TOKEN_SCREEN,
    TOKEN_REF_DIST * TOKEN_SCREEN,
    closeBlend,
  );
}

// ── Ракурс осмотра вблизи ───────────────────────────────────────────────────

/** Центр сценки в её собственных единицах, с учётом сдвига вглубь области. */
const VIEW_CENTER: [number, number, number] = [
  (TOKEN_BOUNDS.xMin + TOKEN_BOUNDS.xMax) / 2 + LAYOUT_OFFSET[0],
  // Не подошва: смотреть в отсыпку значит показать зрителю площадки вместо
  // машин. Высота примерно по балансиру качалки.
  7,
  (TOKEN_BOUNDS.zMin + TOKEN_BOUNDS.zMax) / 2 + LAYOUT_OFFSET[1],
];

/** Высота расстановки, участвующая в кадрировании: мачты ВЛ и вышки. */
const VIEW_HEIGHT = 12;

/**
 * НАСКОЛЬКО КАДР ТЕСНЕЕ ОПИСАННОЙ КОРОБКИ.
 *
 * Дистанция ниже считается по габаритной коробке расстановки, а коробка
 * заведомо шире её силуэта: план промысла — редкая расстановка, а не сплошной
 * ящик, и её углы пусты. Плюс два одиночных выноса — факел и крайние опоры
 * ВЛ, — которым позволено доходить до самого края кадра: ждать, пока они
 * впишутся с запасом, значит отвести камеру ещё на треть и потерять всё
 * остальное.
 *
 * Число подобрано по снятому кадру, а не выведено: силуэт сложной расстановки
 * формулой не берётся. Меняется вместе с ракурсом.
 */
const VIEW_FILL = 0.88;

/**
 * Азимут обзора, отсчёт от юга к востоку. Отрицательный — камера уходит на
 * юго-запад: два ряда качалок вытянуты по параллели и с этой точки читаются
 * уходящими вдаль, а промысловый комплекс с факелом встаёт справа по кадру.
 * Строго с юга ряды слились бы в одну линию.
 */
const VIEW_AZIMUTH = -0.5;

/**
 * Угол возвышения. Пологий настолько, чтобы промысел читался силуэтом —
 * балансиры, факел, эстакады, — и достаточно высокий, чтобы расстановка,
 * ради которой значок и рисовался, ещё была видна планом.
 */
const VIEW_ELEVATION = 0.42;

export interface GeoFrame {
  p: [number, number, number];
  t: [number, number, number];
}

/**
 * КАДР ОСМОТРА ПРОМЫСЛА ВБЛИЗИ.
 *
 * Камера не падает на значок сверху, а обходит его: точка стоит в стороне от
 * площадки, в местной горизонтальной плоскости, и приподнята над ней. Из-за
 * этого подлёт читается движением ПО поверхности глобуса с последующим
 * снижением, а не наездом объектива, и промысел из плана превращается в
 * предмет — появляется перспектива, ближние качалки крупнее дальних, факел
 * встаёт над горизонтом планеты.
 *
 * Дистанция считается, а не подбирается: от габарита сценки, угла обзора и
 * свободной от плашек полосы кадра. Поэтому кадр одинаков на Full HD и на 4K и
 * не разъезжается, когда снизу стоит панель.
 */
export function moldabekCloseFrame(
  fovDeg: number,
  aspect: number,
  reserve: number,
): GeoFrame {
  const { up, east, south } = TOKEN_BASIS;
  const s = TOKEN_WORLD_SCALE;

  const center = TOKEN_ANCHOR.clone()
    .addScaledVector(east, VIEW_CENTER[0] * s)
    .addScaledVector(up, VIEW_CENTER[1] * s)
    .addScaledVector(south, VIEW_CENTER[2] * s);

  /**
   * Дистанция — по силуэту расстановки в кадре, а не по описанной сфере.
   *
   * План промысла вытянут: шестьдесят с лишним единиц по параллели против
   * сорока поперёк, и на пологом ракурсе поперечная ось ещё и сокращается. Если
   * вписывать сферу, кадр встаёт по самому большому измерению, и с боков
   * остаётся пустое поле в треть экрана. Здесь коробка расстановки разложена по
   * экранным осям — вправо и вверх, — и каждая ось ограничивает дистанцию сама.
   *
   * Свободная по высоте доля кадра учитывается тут же: плашка снизу забирает
   * часть экрана, и вписывать сценку в полную высоту значит спрятать её нижний
   * край за плашкой.
   */
  const halfX = (TOKEN_BOUNDS.xMax - TOKEN_BOUNDS.xMin) / 2;
  const halfZ = (TOKEN_BOUNDS.zMax - TOKEN_BOUNDS.zMin) / 2;
  const sinA = Math.abs(Math.sin(VIEW_AZIMUTH));
  const cosA = Math.abs(Math.cos(VIEW_AZIMUTH));
  const sinE = Math.sin(VIEW_ELEVATION);
  const cosE = Math.cos(VIEW_ELEVATION);

  // Вправо по экрану — поперёк направления взгляда; вверх — высота плюс та
  // часть плана, которую разворачивает к зрителю наклон камеры.
  const halfRight = halfX * cosA + halfZ * sinA;
  const halfUp = VIEW_HEIGHT * cosE + (halfX * sinA + halfZ * cosA) * sinE;

  const band = Math.max(0.3, 1 - Math.min(0.8, reserve));
  const tanHalfV = Math.tan((fovDeg * Math.PI) / 360);
  const distance =
    Math.max(halfRight / (tanHalfV * aspect), halfUp / (tanHalfV * band)) * s * VIEW_FILL;

  const horizontal = south
    .clone()
    .multiplyScalar(Math.cos(VIEW_AZIMUTH))
    .addScaledVector(east, Math.sin(VIEW_AZIMUTH));
  const dir = up
    .clone()
    .multiplyScalar(Math.sin(VIEW_ELEVATION))
    .addScaledVector(horizontal, Math.cos(VIEW_ELEVATION))
    .normalize();

  const p = center.clone().addScaledVector(dir, distance);
  return {
    p: [p.x, p.y, p.z],
    t: [center.x, center.y, center.z],
  };
}
