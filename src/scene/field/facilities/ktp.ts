import { box, cone, cyl, pipe, sphere, type Part } from '../kit/parts';

/**
 * Комплектная трансформаторная подстанция — 10 штук на промысле (КТП-202,
 * КТП209 и другие, подписи из чертежа).
 *
 * Понижает напряжение с 10 кВ до 0,4 кВ для приводов станков-качалок, УЭВН и
 * прочих потребителей куста. Именно КТП — то место, где нитка энергетики
 * переходит от магистральной ВЛ-10 кВ к разводке 0,4 кВ (§4.4.1).
 *
 * Узнаваемые признаки: корпус на бетонном основании, проходные изоляторы на
 * крыше, разъединитель на концевой опоре и сетчатое ограждение по периметру.
 */

export function buildKtp(): Part[] {
  const out: Part[] = [];

  // Основание и корпус
  out.push(box('concrete', 3.6, 0.5, 2.8, 0, 0.25, 0));
  out.push(box('painted', 2.6, 2.1, 1.9, 0, 1.55, 0));
  // Односкатная кровля с уклоном назад
  out.push(box('steel', 2.9, 0.1, 2.2, 0, 2.68, -0.05, 0, -0.06));
  // Дверь с жалюзийной решёткой и запором
  out.push(box('steelDark', 1.0, 1.75, 0.07, 0, 1.42, 0.96));
  for (let i = 0; i < 5; i++) {
    out.push(box('steel', 0.8, 0.05, 0.03, 0, 1.75 + i * 0.14, 0.99));
  }
  out.push(sphere('steel', 0.07, 0.42, 1.42, 1.0));

  // Проходные изоляторы высокой стороны: три фарфоровых колонки на крыше
  for (let i = 0; i < 3; i++) {
    const x = -0.7 + i * 0.7;
    out.push(cyl('insulation', 0.09, 0.5, x, 2.95, -0.5, 0, 0, 0, 8));
    for (let k = 0; k < 3; k++) {
      out.push(cone('insulation', 0.17, 0.17, 0.05, x, 2.78 + k * 0.16, -0.5, 0, 0, 0, 10));
    }
    out.push(sphere('steel', 0.07, x, 3.22, -0.5));
  }

  // Концевая опора ВЛ-10 кВ с разъединителем — сюда заходит воздушная линия
  out.push(cyl('concrete', 0.16, 8.5, -2.6, 4.25, -1.4, 0, 0, 0, 8));
  out.push(box('steel', 2.0, 0.12, 0.12, -2.6, 8.1, -1.4));
  for (let i = 0; i < 3; i++) {
    const x = -3.4 + i * 0.8;
    out.push(cyl('insulation', 0.07, 0.34, x, 8.32, -1.4, 0, 0, 0, 8));
    // Спуск от изолятора к проходному вводу корпуса
    out.push(pipe('steelDark', 0.025, [x, 8.32, -1.4], [-0.7 + i * 0.7, 3.22, -0.5], 5));
  }
  // Ящик разъединителя на опоре
  out.push(box('steelDark', 0.45, 0.7, 0.3, -2.6, 5.6, -1.15));

  // Кабельный выход 0,4 кВ в лоток
  out.push(box('steelDark', 0.35, 0.25, 1.4, 1.1, 0.6, 0.9));

  // Сетчатое ограждение: стойки и две нитки по периметру
  const fw = 5.2;
  const fd = 4.4;
  const corners: [number, number][] = [
    [-fw / 2, -fd / 2],
    [fw / 2, -fd / 2],
    [fw / 2, fd / 2],
    [-fw / 2, fd / 2],
  ];
  for (let i = 0; i < 4; i++) {
    const [ax, az] = corners[i];
    const [bx, bz] = corners[(i + 1) % 4];
    const steps = 3;
    for (let s = 0; s <= steps; s++) {
      const t = s / steps;
      out.push(box('steel', 0.07, 1.9, 0.07, ax + (bx - ax) * t, 0.95, az + (bz - az) * t));
    }
    for (const y of [1.85, 1.0]) {
      out.push(pipe('steel', 0.025, [ax, y, az], [bx, y, bz], 5));
    }
  }

  return out;
}
