/** Плоский список тактов с абсолютными границами прогресса [0..1]. */
export interface FlatBeat extends Beat {
  stage: Stage;
  stageIndex: number;
  beatIndex: number;
  /** Глобальный индекс — им управляет кликер-режим. */
  index: number;
  start: number;
  end: number;
}

export const FLAT_BEATS: FlatBeat[] = (() => {
  const total = STAGES.reduce((n, s) => n + s.beats.length, 0);
  const out: FlatBeat[] = [];
  let i = 0;
  STAGES.forEach((stage, stageIndex) => {
    stage.beats.forEach((beat, beatIndex) => {
      out.push({
        ...beat,
        stage,
        stageIndex,
        beatIndex,
        index: i,
        start: i / total,
        end: (i + 1) / total,
      });
      i++;
    });
  });
  return out;
})();

export const TOTAL_BEATS = FLAT_BEATS.length;

/** Полная высота скролл-трека в vh. */
export const TRACK_VH = TOTAL_BEATS * BEAT_SCROLL_VH;

export function beatAt(progress: number): FlatBeat {
  const i = Math.min(TOTAL_BEATS - 1, Math.max(0, Math.floor(progress * TOTAL_BEATS)));
  return FLAT_BEATS[i];
}

/** Прогресс внутри текущего такта, 0..1 — им анимируется всё содержимое. */
export function beatT(progress: number): number {
  const raw = progress * TOTAL_BEATS;
  return Math.min(1, Math.max(0, raw - Math.floor(raw)));
}
