import { useEffect, type RefObject } from 'react';

/**
 * Сколько кадра снизу занято плашкой — доля высоты экрана.
 *
 * Нужна камере: на этапах с нижней плашкой предмет должен вставать в центр
 * СВОБОДНОЙ полосы, а не экрана. Вписанное число здесь не годится: высота
 * плашки зависит от того, как перенеслось содержимое, а перенос — от ширины
 * экрана; плюс общий коэффициент интерфейса упирается в потолок на больших
 * разрешениях. Долю можно только измерить.
 *
 * Значение живёт в мутабельной ссылке, а не в сторе: его пишет наблюдатель
 * размера при каждой перекомпоновке, а читает кадровый цикл. Через состояние
 * React это дало бы перерисовку на каждый пиксель протяжки окна.
 */
export const panelReserve = { current: 0 };

/**
 * Кто последним занял место внизу кадра.
 *
 * Без этого смена плашки давала рывок: React сначала монтирует новую панель, а
 * размонтирование старой происходит следом — и её уборка обнуляла резерв уже
 * ПОСЛЕ того, как новая его выставила. Камера на кадр возвращалась в центр
 * экрана и тут же уезжала обратно, что и читалось как дёрганье фона.
 *
 * Уборка снимает резерв, только если его никто не перехватил.
 */
let owner: string | null = null;

/**
 * Перехватить место, ничего не меняя.
 *
 * Плашка итога встаёт вместо плашки целевого образа, и высота у них разная. Если
 * бы итог мерил себя сам, резерв сменился бы — а вместе с ним и подъём кадра:
 * фон поехал бы по вертикали ровно в момент, когда меняется панель. Здесь итог
 * лишь забирает владение, чтобы уборка предыдущей плашки не сбросила резерв, а
 * величину оставляет прежней. Кадр стоит, меняется только панель.
 */
export function useHoldPanelReserve(id: string): void {
  useEffect(() => {
    owner = id;
    return () => {
      if (owner === id) {
        owner = null;
        panelReserve.current = 0;
      }
    };
  }, [id]);
}

/**
 * Плашка сообщает камере свою высоту.
 *
 * Меряется от верхнего края плашки до низа экрана: снизу у неё ещё отступ, и
 * он тоже занят — предмет туда опускать нельзя.
 */
export function usePanelReserve(id: string, box: RefObject<HTMLDivElement | null>): void {
  useEffect(() => {
    const el = box.current;
    if (!el) return;

    owner = id;

    const measure = () => {
      const rect = el.getBoundingClientRect();
      panelReserve.current = Math.min(
        0.8,
        (globalThis.innerHeight - rect.top) / globalThis.innerHeight,
      );
    };

    measure();
    const ro = new ResizeObserver(measure);
    ro.observe(el);
    globalThis.addEventListener('resize', measure);

    return () => {
      ro.disconnect();
      globalThis.removeEventListener('resize', measure);
      if (owner === id) {
        owner = null;
        panelReserve.current = 0;
      }
    };
  }, [id, box]);
}
