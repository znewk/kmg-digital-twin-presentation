import type { WellRecord } from './fieldData';

/**
 * Эксплуатационные показатели скважины — ИЛЛЮСТРАТИВНЫЕ.
 *
 * Это единственное место в проекте, где числа не имеют первоисточника, и
 * поэтому оно вынесено в отдельный файл с этим комментарием наверху. В реестре
 * фонда, переданном Управлением разработкой КМГ, есть категория, состояние, тип
 * и продуктивный горизонт — но нет ни дебита, ни обводнённости, ни давления
 * (ТЗ §4.1 п.1, §12). Взять их неоткуда, пока не открыт DEV-контур ABAI.
 *
 * Отсюда два обязательных следствия, оба выполнены:
 *  1) любой вывод этих значений в интерфейсе сопровождается пометкой
 *     «иллюстративно» — на показе МЭПМ в зале сидят люди, которые эти цифры
 *     знают, и молчаливая выдумка стоила бы доверия ко всей презентации;
 *  2) значения детерминированы номером скважины. Не ради «стабильности ради
 *     стабильности»: при перерисовке панели дебит не должен меняться на глазах
 *     у зрителя, а при повторном клике по той же скважине — обязан совпасть с
 *     тем, что назвал докладчик минуту назад.
 *
 * Замена на реальные значения — правкой одной этой функции.
 */

export interface WellMetric {
  label: string;
  value: string;
  unit?: string;
}

/** Хеш номера скважины в диапазон 0..1. FNV-1a: короткий и без коллизий на VMB_XXXX. */
function hash01(uwi: string, salt: number): number {
  let h = 0x811c9dc5 ^ salt;
  for (let i = 0; i < uwi.length; i++) {
    h ^= uwi.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return ((h >>> 0) % 100000) / 100000;
}

function span(uwi: string, salt: number, min: number, max: number): number {
  return min + hash01(uwi, salt) * (max - min);
}

/**
 * Показатели скважины по её фактической категории и состоянию.
 *
 * Неработающий фонд показателей не получает: у скважины в консервации нет
 * дебита, и «нарисовать» его означало бы противоречить её же фактическому
 * состоянию, взятому из реестра. Возвращается пустой список — панель в этом
 * случае показывает только фактические поля.
 */
export function wellMetrics(well: WellRecord): WellMetric[] {
  const { uwi, cat, st } = well;
  const running = st === 'active' || st === 'periodic';
  if (!running) return [];

  if (cat === 'inj') {
    return [
      { label: 'Приёмистость', value: span(uwi, 1, 45, 210).toFixed(0), unit: 'м³/сут' },
      { label: 'Давление нагнетания', value: span(uwi, 2, 7.5, 13.8).toFixed(1), unit: 'МПа' },
      { label: 'Коэф. использования', value: span(uwi, 3, 0.82, 0.98).toFixed(2), unit: '' },
    ];
  }

  if (cat === 'oil') {
    const oil = span(uwi, 4, 1.4, 11.6);
    const watercut = span(uwi, 5, 54, 93);
    // Дебит жидкости выводится из нефти и обводнённости, а не выдумывается
    // отдельно: иначе три числа в панели противоречили бы друг другу, и это
    // первое, что заметит промысловик.
    const liquid = oil / (1 - watercut / 100);
    return [
      { label: 'Дебит нефти', value: oil.toFixed(1), unit: 'т/сут' },
      { label: 'Дебит жидкости', value: liquid.toFixed(1), unit: 'м³/сут' },
      { label: 'Обводнённость', value: watercut.toFixed(0), unit: '%' },
      { label: 'Буферное давление', value: span(uwi, 6, 0.7, 2.5).toFixed(1), unit: 'МПа' },
    ];
  }

  if (cat === 'obs') {
    return [
      { label: 'Пластовое давление', value: span(uwi, 7, 8.2, 13.4).toFixed(1), unit: 'МПа' },
      { label: 'Замеров за месяц', value: span(uwi, 8, 2, 8).toFixed(0), unit: '' },
    ];
  }

  return [
    { label: 'Дебит воды', value: span(uwi, 9, 120, 420).toFixed(0), unit: 'м³/сут' },
    { label: 'Динамический уровень', value: span(uwi, 10, 42, 96).toFixed(0), unit: 'м' },
  ];
}
