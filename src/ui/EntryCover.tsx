import { useShow } from '../store/useShow';

/**
 * ЗАСЛОНКА ПЕРЕХОДА К ПРОМЫСЛУ.
 *
 * Глобус и месторождение — разные сцены, и между ними всегда есть кадр, в
 * котором одна уже снята, а другая ещё не собрана. Показывать этот кадр нельзя:
 * он читается сбоем, а не переходом.
 *
 * Заслонка проявляется к концу снижения — камера успевает пройти видимую часть
 * пути, — держится, пока под ней поднимается промысел, и уходит, когда сцена
 * готова. Готовность определяет `FieldEntry`; здесь только показ.
 *
 * Цвет — цвет очистки канваса. На проявлении кадр не темнеет и не мутнеет, а
 * ровно сходит в фон сцены, и граница заслонки не видна.
 *
 * Плашка не масштабируется общим коэффициентом интерфейса и стоит выше него:
 * перекрывать она обязана всё, включая панели.
 */
export function EntryCover() {
  const entry = useShow((s) => s.entry);
  const on = entry !== null;

  return (
    <div
      aria-hidden
      className="pointer-events-none fixed inset-0 z-20"
      style={{
        background: '#050810',
        opacity: on ? 1 : 0,
        /**
         * Проявление отложено: полсекунды снижение идёт на чистом кадре, и
         * только последняя треть пути уходит в фон. Задержка вместе с
         * длительностью укладывается в 1,6 с — ровно столько идёт снижение
         * (`DESCENT_SECONDS`), и к моменту подмены сцены экран уже перекрыт.
         *
         * Уход быстрее и без задержки: зритель ждёт промысел, а не заслонку.
         */
        transition: on
          ? 'opacity 1s cubic-bezier(0.4, 0, 0.9, 0.6) 0.55s'
          : 'opacity 0.7s ease-out',
      }}
    />
  );
}
