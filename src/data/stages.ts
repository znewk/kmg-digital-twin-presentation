/** Точка на поверхности глобуса — цель камеры на гео-этапах. */
const surfaceAt = (lon: number, lat: number): [number, number, number] => {
  const v = lonLatToVec3(lon, lat, GLOBE_R);
  return [v.x, v.y, v.z];
};

