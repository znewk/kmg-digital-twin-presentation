/**
 * РАСКАДРОВКА ПОЛНОГО ЦИКЛА ДОБЫЧИ (ТЗ §4.4).
 *
 * Показ идёт для аудитории, которая не обязана знать нефтедобычу. Значит,
 * цепочка должна не обозначаться, а ОБЪЯСНЯТЬСЯ: кадр за кадром, на одной
 * скважине, с камерой, которая подходит вплотную к тому, о чём идёт речь.
 *
 * Прошлый подход — подсветить разом все 649 трасс нефтесбора — провалился по
 * той же причине, по которой проваливается любая карта вместо рассказа:
 * зритель видит, что «всё связано», и не понимает ни одного звена. Здесь
 * наоборот: одна скважина, одна ГЗУ, один сборный пункт, и каждый следующий
 * кадр отвечает на вопрос, который остался от предыдущего.
 *
 * ЧТО ЗАДАЁТ КАДР. Только смысл: на что смотрим (`look`), с какого расстояния
 * (`framing`), что в это время движется (`play`) и что сказать (`title`,
 * `body`). Координат здесь нет вовсе — они приходят из фактического маршрута,
 * найденного по данным съёмки. Один и тот же кадр «Замер на ГЗУ» покажет ту
 * установку, к которой скважина подключена в реальности, а не ту, которую
 * удобно было бы вписать.
 *
 * ЧЕСТНОСТЬ ЦИФР. Всё, что в теле кадра похоже на измерение — дебит,
 * обводнённость, давление, — иллюстративно и помечено флагом `illustrative`.
 * Состав объектов, длины трасс, номера установок и горизонты — фактические.
 */

/** На что наводится камера. Разрешается по маршруту, найденному в данных. */
export type ShotTarget =
  /** Забой скважины-героини: перфорация, приток из пласта. */
  | { at: 'perforation' }
  /** Ствол целиком — от забоя до устья. */
  | { at: 'bore' }
  /** Устье скважины: качалка, арматура. */
  | { at: 'wellhead' }
  /** Выкидная линия от устья до замерной установки. */
  | { at: 'flowline' }
  /** Замерная установка этой скважины. */
  | { at: 'gzu' }
  /** Куст: скважины, подключённые к той же установке. */
  | { at: 'pad' }
  /** Нефтесборный коллектор от ГЗУ до сборного пункта. */
  | { at: 'collector' }
  /** Сборный пункт. */
  | { at: 'sp' }
  /** Внешний узел за границей съёмки. */
  | { at: 'external'; id: string }
  /** Кустовая насосная станция ППД. */
  | { at: 'kns' }
  /** Водовод от станции к нагнетательной скважине. */
  | { at: 'waterline' }
  /** Нагнетательная скважина. */
  | { at: 'injector' }
  /** Разрез недр под скважиной-героиней. */
  | { at: 'reservoir' }
  /** Весь промысел сверху. */
  | { at: 'field' };

/**
 * Крупность плана.
 *
 * Не число метров, а именно крупность: расстояние считается от габарита того,
 * что попало в кадр. «Деталь» на качалке и «деталь» на сборном пункте — разные
 * дистанции, но одно и то же намерение оператора.
 */
export type Framing = 'detail' | 'object' | 'context' | 'wide';

/** Что оживает в кадре. Сцена читает это поле и включает свою анимацию. */
export type ShotPlay =
  | 'inflow'
  | 'lift'
  | 'pumpjack'
  | 'flow-flowline'
  | 'metering'
  | 'flow-collector'
  | 'separation'
  | 'flow-trunk'
  | 'treatment'
  | 'pumping'
  | 'flow-water'
  | 'injection'
  | 'flood'
  | 'none';

/**
 * Режимы сцены, включаемые кадром.
 *
 * Кадр отвечает не только за камеру, но и за то, что вообще видно. Говорить
 * «нефть входит через перфорацию» и показывать при этом непрозрачный грунт —
 * значит показывать не то, о чём говоришь; а требовать от зрителя вручную
 * найти нужный тумблер посреди показа Президенту нельзя.
 *
 * Поэтому режимы прописаны в самой раскадровке. Кадр включает свои и гасит
 * чужие — при прокрутке назад состояние восстанавливается само, потому что
 * зависит только от текущего кадра, а не от истории переходов.
 */
export interface SceneSetup {
  /** Разнести слои разреза. */
  exploded?: boolean;
  /** Секущая плоскость. */
  clip?: boolean;
  /** Дополнительные слои: сейсмика, заводнение, дренирование, трассы сетей. */
  features?: Partial<
    Record<
      'grid' | 'isolines' | 'seismic' | 'flood' | 'cone' | 'drainage' | 'utilities' | 'traces',
      boolean
    >
  >;
}

export interface Shot {
  id: string;
  /** Нитка: по ней же красится подсветка и узел индикатора. */
  line: 'oil' | 'ppd' | 'gas';
  look: ShotTarget;
  framing: Framing;
  play: ShotPlay;
  /** Заголовок кадра — он же подпись узла на индикаторе пути. */
  title: string;
  /** Что здесь происходит — простыми словами, без отраслевого жаргона. */
  body: string;
  /** Длительность кадра, с. */
  seconds: number;
  /** Что включить в сцене на этом кадре. */
  setup?: SceneSetup;
  /** Модули цифрового двойника, работающие на этом переделе (§4.4.3). */
  modules?: ModuleId[];
  /** В теле есть иллюстративные величины — показать пометку (§7). */
  illustrative?: boolean;
  /** Узел сквозного индикатора «где сейчас нефть». */
  node?: string;
}

