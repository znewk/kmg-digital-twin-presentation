import { box, cone, cyl, ladder, pipe, railing, sphere, torus, type Part } from '../kit/parts';

/**
 * Агрегат ТКРС А-50 (ТЗ §4.4.2).
 *
 * Подъёмная установка на автомобильном шасси: телескопическая мачта, талевая
 * система, лебёдка, выносные опоры. Ставится на скважину, которую выводят из
 * бездействия или ремонтируют, — поэтому сюжетная скважина под ТКРС и выбрана
 * из реестра по фактическому состоянию «бездействие» или «в простое».
 *
 * Ключевая деталь по §4.4.2 — **выложенные НКТ**: при ремонте колонну поднимают
 * из скважины и укладывают на мостки. Без штабеля труб рядом агрегат выглядит
 * приехавшим, но не работающим.
 *
 * По периметру пилота (отчёт обследования): три бригады ПРС, оснащённые
 * датчиками ДЭЛ-140/150 — модель из материалов заказчика, не выдумана.
 *
 * Мачта наклонена к устью, ось агрегата — вдоль X, устье в начале координат.
 */

const MAST_LEN = 22;
/** Наклон мачты от вертикали, рад. */
const TILT = 0.13;

export function buildWorkoverStatic(): Part[] {
  const out: Part[] = [];

  // ── Шасси ────────────────────────────────────────────────────────────────
  const chassisX = 7.5;
  out.push(box('painted', 12.5, 1.1, 2.7, chassisX, 1.35, 0));
  out.push(box('steelDark', 12.8, 0.35, 2.9, chassisX, 0.72, 0));

  // Кабина
  out.push(box('painted', 2.6, 2.3, 2.6, 13.4, 2.35, 0));
  out.push(box('glass', 0.1, 1.1, 2.2, 14.66, 2.75, 0));
  out.push(box('glass', 2.2, 1.0, 0.08, 13.4, 2.75, 1.32));

  // Колёса: три оси, задняя сдвоенная
  for (const [wx, dual] of [
    [12.2, false],
    [4.4, true],
    [2.2, true],
  ] as const) {
    for (const side of [-1, 1]) {
      const z = side * 1.35;
      out.push(cyl('steelDark', 0.62, 0.42, wx, 0.62, z, Math.PI / 2, 0, 0, 12));
      if (dual) out.push(cyl('steelDark', 0.62, 0.42, wx, 0.62, z + side * 0.44, Math.PI / 2, 0, 0, 12));
      out.push(cyl('steel', 0.26, 0.5, wx, 0.62, z, Math.PI / 2, 0, 0, 10));
    }
  }

  // Выносные опоры (аутригеры) — агрегат работает только на них
  for (const [ox, oz] of [
    [1.6, -1.9],
    [1.6, 1.9],
    [11.0, -1.9],
    [11.0, 1.9],
  ] as const) {
    out.push(box('steel', 0.32, 0.32, 1.4, ox, 1.1, oz));
    out.push(cyl('steel', 0.16, 1.1, ox, 0.55, oz * 1.35, 0, 0, 0, 8));
    out.push(box('steelDark', 0.9, 0.18, 0.9, ox, 0.09, oz * 1.35));
  }

  // ── Мачта ────────────────────────────────────────────────────────────────
  // Двухсекционная телескопическая: нижняя секция шире верхней.
  const topX = -Math.sin(TILT) * MAST_LEN;
  const topY = 2.0 + Math.cos(TILT) * MAST_LEN;

  for (const dz of [-0.62, 0.62]) {
    out.push(pipe('steel', 0.15, [1.2, 2.0, dz], [topX + 0.2, topY, dz * 0.55], 6));
  }
  // Связи мачты
  for (let i = 1; i <= 8; i++) {
    const t = i / 9;
    const x = 1.2 + (topX + 0.2 - 1.2) * t;
    const y = 2.0 + (topY - 2.0) * t;
    const halfZ = 0.62 + (0.62 * 0.55 - 0.62) * t;
    out.push(pipe('steel', 0.06, [x, y, -halfZ], [x, y, halfZ], 5));
    const p = (i - 1) / 9;
    const px = 1.2 + (topX + 0.2 - 1.2) * p;
    const py = 2.0 + (topY - 2.0) * p;
    out.push(pipe('steel', 0.05, [px, py, -halfZ], [x, y, halfZ], 5));
  }

  // Кронблок и талевая система
  out.push(box('steelDark', 1.2, 0.6, 1.5, topX, topY + 0.3, 0));
  for (const dz of [-0.35, 0, 0.35]) {
    out.push(torus('steel', 0.3, 0.07, topX, topY + 0.3, dz, 0, Math.PI / 2, 0));
  }
  // Оттяжки мачты
  for (const side of [-1, 1]) {
    out.push(pipe('steelDark', 0.03, [topX, topY * 0.92, 0], [10, 0.3, side * 4.5], 5));
  }

  // Лебёдка на раме
  out.push(box('painted', 2.6, 1.5, 2.2, 5.6, 2.65, 0));
  out.push(cyl('steel', 0.5, 1.9, 5.6, 2.9, 0, 0, 0, Math.PI / 2, 12));

  // ── Устьевая часть ───────────────────────────────────────────────────────
  out.push(cyl('steelDark', 0.55, 1.4, 0, 0.7, 0, 0, 0, 0, 12));
  out.push(torus('steelDark', 0.62, 0.09, 0, 1.35, 0, Math.PI / 2));
  // Рабочая площадка у устья
  out.push(box('steel', 3.2, 0.1, 3.0, -1.4, 0.75, 0));
  out.push(...railing(-1.4, 0.8, 0, 3.2, 3.0, 1.05));
  out.push(...ladder(-3.0, 0, 0, 0.8));

  // ── Выложенные НКТ на мостках ────────────────────────────────────────────
  // Поднятая из скважины колонна: два стеллажа, трубы в три ряда.
  for (const side of [-1, 1]) {
    const z = side * 4.6;
    for (const sx of [-4, 2]) {
      out.push(box('steelDark', 0.22, 0.55, 2.4, sx, 0.75, z));
    }
    for (let row = 0; row < 3; row++) {
      const count = 6 - row;
      for (let i = 0; i < count; i++) {
        out.push(
          cyl(
            'pipe',
            0.06,
            9.5,
            -1,
            1.12 + row * 0.13,
            z + (i - (count - 1) / 2) * 0.14,
            0,
            0,
            Math.PI / 2,
            6,
          ),
        );
      }
    }
  }

  // ── Ёмкость долива и обвязка ─────────────────────────────────────────────
  out.push(cyl('insulation', 1.0, 3.6, -6, 1.5, 3.4, 0, 0, Math.PI / 2, 14));
  out.push(cone('insulation', 0.5, 1.0, 0.4, -8.0, 1.5, 3.4, 0, 0, Math.PI / 2, 14));
  for (const dx of [-4.8, -7.2]) out.push(box('steelDark', 0.35, 0.9, 2.0, dx, 0.55, 3.4));
  out.push(pipe('pipe', 0.09, [-6, 0.7, 3.4], [-1.2, 0.7, 0.6]));

  // ── Датчик ДЭЛ-140/150 на мачте ──────────────────────────────────────────
  // По периметру пилота им оснащены три бригады ПРС.
  out.push(box('painted', 0.5, 0.7, 0.45, 0.9, 6.4, 0.85));
  out.push(sphere('accent', 0.17, 0.9, 6.9, 0.85));
  out.push(pipe('steelDark', 0.025, [0.9, 6.05, 0.85], [1.2, 2.2, 0.85], 4));

  // Будка бригады
  out.push(box('painted', 3.4, 2.4, 2.4, -7.5, 1.2, -4.2));
  out.push(box('glass', 1.0, 0.8, 0.08, -7.5, 1.7, -3.0));
  out.push(box('steelDark', 0.85, 1.9, 0.08, -6.2, 0.95, -3.0));

  return out;
}
