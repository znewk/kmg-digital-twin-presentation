import {
  box,
  fence,
  cone,
  cyl,
  flange,
  gableRoof,
  ladder,
  pipe,
  pipeRun,
  railing,
  sphere,
  torus,
  valve,
  type Part,
} from '../kit/parts';

/**
 * Кустовая насосная станция ППД — КНС-2, КНС-3, КНС-4.
 *
 * Технология: подготовленная вода приходит на приём, насосы ЦНС поднимают
 * давление до нагнетательного и через распределительную гребёнку отправляют
 * её по водоводам на нагнетательные скважины. Отсюда и узнаваемый вид —
 * с одной стороны один толстый низконапорный вход, с другой веер тонких
 * ниток высокого давления, каждая со своей задвижкой и расходомером.
 *
 * На Восточном Молдабеке ППД особенно нагружена: 210 нагнетательных скважин
 * на 851 нефтяную — доля, характерная для высоковязкой нефти, которую без
 * поддержания давления с залежи не поднять.
 *
 * Марки насосов в переданных материалах не указаны — габариты типовые для
 * ЦНС горизонтального исполнения.
 */

const PAD_W = 26;
const PAD_D = 16;
const HALL_W = 17;
const HALL_H = 5.4;
const HALL_D = 8.4;

export function buildKns(): Part[] {
  const out: Part[] = [];

  // ── Площадка и обваловка ─────────────────────────────────────────────────
  out.push(box('concrete', PAD_W, 0.4, PAD_D, 0, 0.2, 0));
  for (const [dx, dz, w, d] of [
    [0, -PAD_D / 2 - 0.8, PAD_W + 3, 1.6],
    [0, PAD_D / 2 + 0.8, PAD_W + 3, 1.6],
    [-PAD_W / 2 - 0.8, 0, 1.6, PAD_D + 3],
    [PAD_W / 2 + 0.8, 0, 1.6, PAD_D + 3],
  ] as const) {
    out.push(box('concrete', w, 0.7, d, dx, 0.35, dz));
  }

  // ── Насосный зал ─────────────────────────────────────────────────────────
  const hallY = 0.4;
  out.push(box('painted', HALL_W, HALL_H, HALL_D, -2, hallY + HALL_H / 2, 1.6));
  out.push(
    ...gableRoof('steel', HALL_W + 0.5, HALL_D + 0.5, hallY + HALL_H, 1.1).map((p) => {
      p.matrix.elements[12] += -2;
      p.matrix.elements[14] += 1.6;
      return p;
    }),
  );

  // Ворота, двери, ленточное остекление и вентиляция — насосный зал всегда
  // с большими воротами: агрегат меняют краном через них.
  out.push(box('steelDark', 3.6, 3.8, 0.12, -2, hallY + 1.9, -2.66));
  out.push(box('steel', 0.1, 3.8, 0.14, -2, hallY + 1.9, -2.72));
  for (let i = 0; i < 5; i++) {
    out.push(box('glass', 1.5, 0.8, 0.08, -8 + i * 2.9, hallY + 4.2, -2.66));
  }
  out.push(box('steelDark', 1.0, 2.1, 0.1, 5.2, hallY + 1.05, -2.66));
  for (let i = 0; i < 3; i++) {
    out.push(cyl('steel', 0.34, 0.7, -7 + i * 4.5, hallY + HALL_H + 1.4, 1.6, 0, 0, 0, 10));
    out.push(cone('steelDark', 0.44, 0.34, 0.22, -7 + i * 4.5, hallY + HALL_H + 1.85, 1.6, 0, 0, 0, 10));
  }

  // ── Приёмный (низконапорный) коллектор ───────────────────────────────────
  const inZ = -PAD_D / 2 - 1.2;
  out.push(
    ...pipeRun('pipeWater', 0.34, [
      [-11, 1.1, inZ],
      [-11, 1.1, -3.4],
      [-9.2, 1.1, -3.4],
    ]),
  );
  out.push(...valve(-11, 1.25, -5.6, 1.2));
  out.push(flange('steelDark', 0.5, -11, 1.1, -4.2, Math.PI / 2));

  // Буферная ёмкость на приёме: гасит пульсации и держит подпор.
  out.push(cyl('insulation', 1.5, 7.2, -10.4, 2.1, 5.6, 0, 0, Math.PI / 2, 16));
  out.push(cone('insulation', 0.7, 1.5, 0.7, -14.35, 2.1, 5.6, 0, 0, Math.PI / 2, 16));
  out.push(cone('insulation', 1.5, 0.7, 0.7, -6.45, 2.1, 5.6, 0, 0, Math.PI / 2, 16));
  for (const dx of [-13, -7.8]) {
    out.push(box('steelDark', 0.5, 1.0, 2.6, dx, 0.9, 5.6));
    out.push(torus('steel', 1.52, 0.06, dx, 2.1, 5.6, 0, 0, Math.PI / 2));
  }
  out.push(...ladder(-10.4, 0.4, 4.0, 3.3));

  // ── Насосные агрегаты ────────────────────────────────────────────────────
  // Три агрегата: рабочие плюс резерв — по отчёту обследования профиль-дизайны
  // считаются «только ЦНС с учётом резерва».
  for (let i = 0; i < 3; i++) {
    const x = -8 + i * 4.6;
    const y = hallY + 0.5;
    // Рама, электродвигатель, муфта и сам насос
    out.push(box('steelDark', 3.8, 0.35, 1.5, x, y, 1.6));
    out.push(cyl('painted', 0.55, 1.9, x - 1.0, y + 0.75, 1.6, 0, 0, Math.PI / 2, 14));
    out.push(cyl('steel', 0.16, 0.5, x + 0.15, y + 0.75, 1.6, 0, 0, Math.PI / 2, 8));
    out.push(cyl('steel', 0.48, 1.7, x + 1.15, y + 0.75, 1.6, 0, 0, Math.PI / 2, 14));
    out.push(cone('steel', 0.28, 0.48, 0.3, x + 2.05, y + 0.75, 1.6, 0, 0, Math.PI / 2, 12));
    // Патрубки всасывания и нагнетания
    out.push(pipe('pipeWater', 0.2, [x + 1.15, y + 0.3, 1.6], [x + 1.15, y - 0.2, 1.6]));
    out.push(pipe('pipeWater', 0.16, [x + 1.15, y + 1.25, 1.6], [x + 1.15, y + 2.3, 1.6]));
    out.push(flange('steelDark', 0.26, x + 1.15, y + 1.3, 1.6));
  }

  // ── Нагнетательный коллектор и распределительная гребёнка ────────────────
  const outZ = PAD_D / 2 - 1.6;
  const manY = 2.4;
  out.push(pipe('pipeWater', 0.3, [-10, manY, outZ], [10.5, manY, outZ]));
  for (const x of [-9, -4, 1, 6, 10]) {
    out.push(box('steel', 0.16, manY - 0.4, 0.16, x, 0.4 + (manY - 0.4) / 2, outZ));
  }

  // Восемь ниток высокого давления на нагнетательные скважины: задвижка,
  // расходомер и обратный клапан на каждой — узнаваемый «веер» КНС.
  for (let i = 0; i < 8; i++) {
    const x = -9 + i * 2.6;
    out.push(pipe('pipeWater', 0.11, [x, manY, outZ], [x, manY, outZ + 2.2]));
    out.push(pipe('pipeWater', 0.11, [x, manY, outZ + 2.2], [x, 0.9, outZ + 2.2]));
    out.push(pipe('pipeWater', 0.11, [x, 0.9, outZ + 2.2], [x, 0.9, PAD_D / 2 + 1.6]));
    out.push(...valve(x, manY + 0.15, outZ + 0.9, 0.7));
    out.push(cyl('accent', 0.17, 0.42, x, 1.7, outZ + 2.2, 0, 0, 0, 10));
    out.push(sphere('steelDark', 0.16, x, 0.9, outZ + 1.4));
  }

  // ── Дренажная ёмкость и мелочь ───────────────────────────────────────────
  out.push(cyl('steelDark', 1.1, 0.5, 11.5, 0.5, -4.5, 0, 0, 0, 14));
  out.push(cyl('steel', 0.32, 0.9, 11.5, 1.0, -4.5, 0, 0, 0, 10));
  out.push(box('steel', 4.2, 0.1, 3.0, 11.2, 0.46, 3.0));
  out.push(...railing(11.2, 0.5, 3.0, 4.2, 3.0, 1.05));

  // Щит управления и кабельный лоток вдоль стены зала
  out.push(box('painted', 2.4, 2.2, 0.9, 7.6, hallY + 1.1, 4.2));
  out.push(box('steelDark', 0.4, 0.12, 9.0, -2, hallY + 3.4, 6.0));

  // Ограждение с воротами: КНС — объект ППД под высоким давлением
  out.push(...fence(PAD_W + 5, PAD_D + 5, { guard: false }));

  // Мачта освещения
  out.push(cyl('steel', 0.11, 8.5, -12.5, 4.65, -6.2, 0, 0, 0, 8));
  out.push(box('steelDark', 1.4, 0.18, 0.32, -11.9, 8.9, -6.2, 0, -0.25));

  return out;
}
