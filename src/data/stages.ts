export interface Stage {
  id: StageId;
  /** Номер блока сценария; null — служебный этап (вход/итог). */
  scenarioBlock: number | null;
  /** Докладчик по сценарию — в кадр не выводится, нужен для темпа. */
  speaker?: T;
  /** Минуты по сценарию. */
  minutes?: number;
  /** Заголовок этапа в титрах. */
  chapter: T;
  title: T;
  lead?: T;
  /** Контур двойника, задаёт акцентный цвет. */
  twin?: 'plast' | 'skv' | 'dob' | null;
  beats: Beat[];
}

