import {
  box,
  cone,
  cyl,
  flange,
  gableRoof,
  ladder,
  pipe,
  pipeRun,
  railing,
  torus,
  valve,
  type Part,
} from '../kit/parts';

/**
 * Групповая замерная установка — 41 штука на промысле, ГЗУ-1…ГЗУ-52.
 *
 * Что это по технологии и почему выглядит именно так. В ГЗУ сходятся выкидные
 * линии куста — отсюда гребёнка подводящих труб с одной стороны. Внутри
 * многоходовой переключатель скважин (ПСМ) поочерёдно направляет одну из
 * скважин на замерный сепаратор, остальные идут мимо, в общий коллектор.
 * Отсюда два выхода: общая линия на нефтесбор и замерная петля через сепаратор.
 * Оборудование стоит в утеплённом блок-боксе — на Прикаспии зимой иначе
 * замерзает, — а сепаратор вынесен наружу и виден целиком.
 *
 * Габариты типовые для АГЗУ на 10–14 скважин: блок-бокс около 6 × 3 м,
 * основание 9 × 6 м. Паспорта конкретной установки в переданных материалах
 * нет — марка ГЗУ в чертеже и отчёте не указана, есть только номера.
 *
 * Ориентация: гребёнка подводящих линий смотрит в −Z, выход на нефтесбор в +Z.
 * При расстановке установка разворачивается лицом к своему кусту.
 */

const PAD_W = 9;
const PAD_D = 6;
const BOX_W = 6;
const BOX_H = 2.9;
const BOX_D = 3;

export function buildGzu(): Part[] {
  const out: Part[] = [];

  // ── Основание и обваловка ────────────────────────────────────────────────
  out.push(box('concrete', PAD_W, 0.35, PAD_D, 0, 0.18, 0));
  // Обваловка — низкий земляной вал по периметру площадки, обязателен по
  // требованиям к объектам с нефтесодержащей средой.
  for (const [dx, dz, w, d] of [
    [0, -PAD_D / 2 - 0.6, PAD_W + 2, 1.2],
    [0, PAD_D / 2 + 0.6, PAD_W + 2, 1.2],
    [-PAD_W / 2 - 0.6, 0, 1.2, PAD_D + 2],
    [PAD_W / 2 + 0.6, 0, 1.2, PAD_D + 2],
  ] as const) {
    out.push(box('concrete', w, 0.5, d, dx, 0.25, dz));
  }

  // ── Блок-бокс ────────────────────────────────────────────────────────────
  const boxY = 0.35;
  out.push(box('painted', BOX_W, BOX_H, BOX_D, -0.6, boxY + BOX_H / 2, 0.8));
  out.push(...gableRoof('steel', BOX_W + 0.4, BOX_D + 0.4, boxY + BOX_H, 0.55).map((p) => {
    p.matrix.elements[12] += -0.6;
    p.matrix.elements[14] += 0.8;
    return p;
  }));

  // Дверь с козырьком, окно и вентиляционная решётка — без них блок-бокс
  // читается глухим контейнером, а не помещением с оборудованием.
  out.push(box('steelDark', 0.9, 1.95, 0.08, -3.1, boxY + 0.98, 0.8, Math.PI / 2));
  out.push(box('steel', 1.2, 0.06, 0.6, -3.35, boxY + 2.1, 0.8));
  out.push(box('glass', 0.75, 0.55, 0.06, -1.4, boxY + 1.9, -0.72));
  for (let i = 0; i < 4; i++) {
    out.push(box('steelDark', 0.62, 0.06, 0.04, 1.6, boxY + 1.2 + i * 0.14, -0.72));
  }
  // Ступень у входа
  out.push(box('steel', 1.1, 0.12, 0.5, -3.35, boxY + 0.06, 0.8));

  // ── Гребёнка подводящих выкидных линий ───────────────────────────────────
  // Десять ниток от скважин куста заходят с северной стороны в общий
  // приёмный коллектор. Число выбрано по типовой ёмкости АГЗУ.
  const inletZ = -PAD_D / 2 - 1.4;
  const manifoldZ = -1.5;
  const inletY = 0.75;

  out.push(pipe('pipe', 0.18, [-3.6, inletY, manifoldZ], [3.6, inletY, manifoldZ]));
  for (let i = 0; i < 10; i++) {
    const x = -3.3 + i * 0.73;
    out.push(pipe('pipe', 0.07, [x, inletY, inletZ], [x, inletY, manifoldZ]));
    out.push(flange('steelDark', 0.11, x, inletY, manifoldZ + 0.12, Math.PI / 2));
    // Отсечная задвижка на каждой нитке — по одной на скважину.
    out.push(...valve(x, inletY + 0.1, inletZ + 0.55, 0.55));
  }

  // ── Переключатель скважин (ПСМ) ──────────────────────────────────────────
  // Многоходовой кран: одна скважина уходит на замер, остальные — мимо.
  out.push(cyl('steelDark', 0.62, 1.15, 0.4, inletY + 0.3, manifoldZ + 0.9, 0, 0, 0, 14));
  out.push(cone('steel', 0.4, 0.62, 0.3, 0.4, inletY + 0.98, manifoldZ + 0.9, 0, 0, 0, 14));
  out.push(cyl('steel', 0.09, 0.7, 0.4, inletY + 1.4, manifoldZ + 0.9, 0, 0, 0, 8));
  out.push(torus('accent', 0.3, 0.05, 0.4, inletY + 1.75, manifoldZ + 0.9, Math.PI / 2));

  // ── Замерной сепаратор ───────────────────────────────────────────────────
  // Вертикальная ёмкость с эллиптическими днищами на опорной юбке. Именно на
  // ней и считается дебит скважины, поставленной на замер.
  const sx = 3.4;
  const sz = 1.5;
  const sepY = 0.35;
  out.push(cyl('insulation', 0.62, 2.6, sx, sepY + 1.75, sz, 0, 0, 0, 16));
  out.push(cone('insulation', 0.28, 0.62, 0.42, sx, sepY + 3.26, sz, 0, 0, 0, 16));
  out.push(cone('insulation', 0.62, 0.28, 0.42, sx, sepY + 0.24, sz, 0, 0, 0, 16));
  out.push(cyl('steelDark', 0.45, 0.5, sx, sepY + 0.25, sz, 0, 0, 0, 12));
  // Кольца жёсткости и люк-лаз
  for (const dy of [1.1, 2.4]) {
    out.push(torus('steel', 0.63, 0.05, sx, sepY + dy, sz, Math.PI / 2));
  }
  out.push(cyl('steelDark', 0.26, 0.16, sx - 0.6, sepY + 2.2, sz, 0, 0, Math.PI / 2, 10));
  // Уровнемерное стекло и предохранительный клапан на верхнем днище
  out.push(box('glass', 0.1, 1.5, 0.06, sx + 0.66, sepY + 1.8, sz));
  out.push(cyl('steel', 0.1, 0.5, sx + 0.22, sepY + 3.6, sz, 0, 0, 0, 8));
  out.push(...ladder(sx - 0.95, sepY, sz, 3.1));

  // ── Обвязка: замерная петля и выход на нефтесбор ─────────────────────────
  const outZ = PAD_D / 2 + 1.4;

  // Из переключателя на сепаратор
  out.push(
    ...pipeRun('pipe', 0.1, [
      [0.4, inletY + 0.3, manifoldZ + 1.5],
      [sx - 1.1, inletY + 0.3, manifoldZ + 1.5],
      [sx - 1.1, sepY + 2.9, manifoldZ + 1.5],
      [sx - 1.1, sepY + 2.9, sz],
      [sx - 0.62, sepY + 2.9, sz],
    ]),
  );
  // Из сепаратора обратно в общий коллектор
  out.push(
    ...pipeRun('pipe', 0.1, [
      [sx, sepY + 0.1, sz],
      [sx, 0.55, outZ - 0.9],
      [1.2, 0.55, outZ - 0.9],
    ]),
  );
  // Общий коллектор на нефтесбор
  out.push(
    ...pipeRun('pipe', 0.2, [
      [-3.6, inletY, manifoldZ],
      [-3.6, 0.62, outZ - 0.9],
      [1.2, 0.62, outZ - 0.9],
      [1.2, 0.62, outZ],
    ]),
  );
  out.push(...valve(1.2, 0.75, outZ - 0.45, 0.8));
  out.push(flange('steelDark', 0.28, 1.2, 0.62, outZ - 0.1, Math.PI / 2));

  // Опоры под трубы: нитки не висят в воздухе.
  for (const x of [-3.6, -1.2, 1.2]) {
    out.push(box('steel', 0.12, 0.5, 0.12, x, 0.32, outZ - 0.9));
  }

  // ── Площадка обслуживания и мелочь ───────────────────────────────────────
  out.push(box('steel', 2.6, 0.08, 1.8, sx - 0.2, sepY + 0.04, sz + 1.9));
  out.push(...railing(sx - 0.2, sepY + 0.08, sz + 1.9, 2.6, 1.8, 1.0));

  // Кабельный ввод и щит КИПиА на стене блок-бокса
  out.push(box('steelDark', 0.5, 0.7, 0.22, -3.0, boxY + 1.5, -0.7));
  out.push(pipe('steelDark', 0.05, [-3.0, boxY + 1.15, -0.7], [-3.0, 0.1, -0.7]));

  // Мачта освещения площадки
  out.push(cyl('steel', 0.09, 5.2, -4.0, 2.95, -2.2, 0, 0, 0, 8));
  out.push(box('steelDark', 0.5, 0.16, 0.28, -3.8, 5.5, -2.2, 0, -0.3));

  return out;
}
